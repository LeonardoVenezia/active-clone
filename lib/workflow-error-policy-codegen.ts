import type { WorkflowEdge, WorkflowNode } from "./workflow-store";

/** Same graph runner in both export formats. Callbacks contain only step execution. */
export function generateErrorPolicyRunner(
  nodes: WorkflowNode[],
  edges: WorkflowEdge[],
  callbacks: string[],
): string[] {
  const metadata = nodes.map(n => ({ id: n.id, type: n.data.type, label: n.data.label || n.id, enabled: n.data.enabled !== false, action: n.data.config?.actionType, policy: n.data.config?.onError }));
  return [
    `  const __policyNodes: {id:string;type:string;label:string;enabled:boolean;action?:unknown;policy?:unknown}[] = ${JSON.stringify(metadata)};`,
    `  const __policyEdges = ${JSON.stringify(edges.map(e => [e.source, e.target]))};`,
    `  function __policyField(data:unknown,path:string):unknown { return path.split(".").reduce<unknown>((v,k)=>{ const parts=k.replace(/\\[(\\d+)\\]/g,".$1").split("."); for(const p of parts) v=v==null?undefined:(v as Record<string,unknown>)[p]; return v; },data); }`,
    `  function __policyConfig(config:Record<string,unknown>):Record<string,unknown> { return Object.fromEntries(Object.entries(config).map(([key,value])=>[key,typeof value!=="string" ? value : value.replace(/\\{\\{@([^:]+):([^}]+)\\}\\}/g,(match,id,rest,offset,whole)=>{const o=__policyOutputs[id.replace(/[^a-zA-Z0-9]/g,"_")]; if(!o)return match; const dot=rest.indexOf("."); const v=dot<0?o.data:__policyField(o.data,rest.slice(dot+1)); const raw=v==null?"":typeof v==="object"?JSON.stringify(v):String(v); let inside=false; if(["arguments","httpBody","httpHeaders","input","operations","responseSchema"].includes(key)) {for(let i=0;i<offset;i++){ if(whole[i]==="\\\\")i++;else if(whole[i]==='"')inside=!inside;}} return inside?JSON.stringify(raw).slice(1,-1):raw;})])); }`,
    "  const __policyCallbacks: Record<string, () => Promise<unknown>> = {",
    ...callbacks,
    "  };",
    `  const __policyResults: Record<string, {success:boolean; data?:unknown; error?:string}> = {};`,
    `  const __policyOutputs: Record<string, {label:string; data:any}> = {};`,
    `  const __policyVisited = new Set<string>();`,
    `  const __policyPropagated = new Set<string>();`,
    `  const __policyParents = new Map<string, Set<string>>();`,
    `  const __policyArrivals = new Map<string, Set<string>>();`,
    // Ignore unreachable parents, like the platform executor.
    `  const __policyRoots = __policyNodes.filter(n => n.type === "trigger" && !__policyEdges.some(e => e[1] === n.id));`,
    `  const __policyReachable = new Set<string>();`,
    `  function __policyWalk(id:string) { if (__policyReachable.has(id)) return; __policyReachable.add(id); for (const e of __policyEdges) if(e[0]===id) __policyWalk(e[1]); }`,
    `  for(const n of __policyRoots) __policyWalk(n.id);`,
    `  for(const [s,t] of __policyEdges) if(__policyReachable.has(s)) { const p=__policyParents.get(t)||new Set<string>(); p.add(s); __policyParents.set(t,p); }`,
    `  function __policyError(e:unknown):string { if(typeof e === "string") return e || "El paso falló."; if(e && typeof e === "object") { const o=e as {message?:unknown;error?:unknown}; if(typeof o.message === "string") return o.message; if(o.error!==undefined) return __policyError(o.error); } return "El paso falló."; }`,
    `  async function __policyRelease(id:string, active:boolean):Promise<void> {`,
    `    if(__policyPropagated.has(id)) return; __policyPropagated.add(id);`,
    `    await Promise.all([...new Set(__policyEdges.filter(e=>e[0]===id).map(e=>e[1]))].map(async child=>{`,
    `      const seen=__policyArrivals.get(child)||new Set<string>(); if(seen.has(id)) return; seen.add(id); __policyArrivals.set(child,seen);`,
    `      if(active) await __policyRun(child);`,
    `      else if(seen.size >= (__policyParents.get(child)?.size||0) && !__policyVisited.has(child)) await __policyRelease(child,false);`,
    `    }));`,
    `  }`,
    `  async function __policyRun(id:string):Promise<void> {`,
    `    if(__policyVisited.has(id)) return; __policyVisited.add(id);`,
    `    const node=__policyNodes.find(n=>n.id===id); if(!node) return;`,
    `    const key=id.replace(/[^a-zA-Z0-9]/g,"_");`,
    `    if(!node.enabled) { __policyOutputs[key]={label:node.label,data:null}; await __policyRelease(id,true); return; }`,
    `    let data:unknown; let error:string|undefined;`,
    `    try {`,
    `      data=await __policyCallbacks[id]();`,
    `      if(node.type!=="trigger" && data && typeof data==="object" && (data as {success?:boolean}).success===false) error=__policyError((data as {error?:unknown}).error);`,
    `    } catch(e) { error=__policyError(e); }`,
    `    __policyResults[id]=error ? {success:false,error,data} : {success:true,data};`,
    `    __policyOutputs[key]={label:node.label,data:error ? {...(data && typeof data==="object" ? data : {}),success:false,error} : data};`,
    `    if(!error) {`,
    `      const active=node.action!=="Condition" || (data as {condition?:boolean})?.condition===true;`,
    `      await __policyRelease(id,active);`,
    `    } else await __policyRelease(id,node.policy==="continue" && node.action!=="Approval");`,
    `  }`,
    `  await Promise.all(__policyRoots.map(n=>__policyRun(n.id)));`,
    `  return {success:Object.values(__policyResults).every(r=>r.success),results:__policyResults,outputs:__policyOutputs};`,
  ];
}
